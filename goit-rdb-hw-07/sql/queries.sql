--  База даних: mydb (датасет Теми 3 / Northwind), таблиця orders
--  СУБД: MySQL 8.x
-- =====================================================================
USE mydb;

-- ---------------------------------------------------------------------
-- Завдання 1. Витягти з date рік, місяць і число — 3 окремі атрибути
--   поряд з id та оригінальним date (усього 5 атрибутів).
-- ---------------------------------------------------------------------
SELECT
    id,
    date,
    YEAR(date)  AS `year`,
    MONTH(date) AS `month`,
    DAY(date)   AS `day`
FROM orders;

-- ---------------------------------------------------------------------
-- Завдання 2. Додати до date один день. Вивести id, оригінальний date
--   та результат додавання.
-- ---------------------------------------------------------------------
SELECT
    id,
    date,
    DATE_ADD(date, INTERVAL 1 DAY) AS date_plus_one_day
FROM orders;

-- ---------------------------------------------------------------------
-- Завдання 3. Кількість секунд від початку відліку (timestamp) для date.
--   Функція UNIX_TIMESTAMP(). Вивести id, оригінальний date, результат.
-- ---------------------------------------------------------------------
SELECT
    id,
    date,
    UNIX_TIMESTAMP(date) AS timestamp_seconds
FROM orders;

-- ---------------------------------------------------------------------
-- Завдання 4. Кількість рядків orders із date у межах
--   між 1996-07-10 00:00:00 та 1996-10-08 00:00:00.
-- ---------------------------------------------------------------------
SELECT COUNT(*) AS rows_count
FROM orders
WHERE date BETWEEN '1996-07-10 00:00:00' AND '1996-10-08 00:00:00';

-- ---------------------------------------------------------------------
-- Завдання 5. Вивести id, date та JSON-об'єкт {"id": ..., "date": ...}.
--   Функція JSON_OBJECT().
-- ---------------------------------------------------------------------
SELECT
    id,
    date,
    JSON_OBJECT('id', id, 'date', date) AS json_object
FROM orders;
