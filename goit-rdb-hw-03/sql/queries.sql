USE mydb;

-- ---------------------------------------------------------------------
-- Завдання 1. Вибірка стовпчиків
-- ---------------------------------------------------------------------

-- 1a. Усі стовпчики таблиці products (wildcard "*")
SELECT *
FROM products;

-- 1b. Тільки стовпчики name та phone з таблиці shippers
SELECT name, phone
FROM shippers;

-- ---------------------------------------------------------------------
-- Завдання 2. Середнє, максимальне та мінімальне значення price у products
-- ---------------------------------------------------------------------
SELECT
    AVG(price) AS avg_price,
    MAX(price) AS max_price,
    MIN(price) AS min_price
FROM products;

-- ---------------------------------------------------------------------
-- Завдання 3. Унікальні пари (category_id, price), сортування за спаданням
--             price, перші 10 рядків
-- ---------------------------------------------------------------------
SELECT DISTINCT category_id, price
FROM products
ORDER BY price DESC
LIMIT 10;

-- ---------------------------------------------------------------------
-- Завдання 4. Кількість продуктів із ціною в межах від 20 до 100 включно
-- ---------------------------------------------------------------------
SELECT COUNT(*) AS products_20_100
FROM products
WHERE price BETWEEN 20 AND 100;

-- ---------------------------------------------------------------------
-- Завдання 5. Кількість продуктів та середня ціна для кожного постачальника
-- ---------------------------------------------------------------------
SELECT
    supplier_id,
    COUNT(*)   AS products_count,
    AVG(price) AS avg_price
FROM products
GROUP BY supplier_id;
